#!/usr/bin/env python3
"""
Build-time helpers for custom DC configuration.

Reads the DC config endpoint URL from blah-server.config.url (placed next to
this script), fetches the configuration at build time, and writes a C++ source
file with literal CustomDcConfig values so that the runtime incurs zero parsing
overhead.

To change the endpoint, edit blah-server.config.url — do not hardcode the URL
in this script.
"""

import argparse
import json
import os
import urllib.request

HEADER = '// Auto-generated by Telegram/build/custom_dc_config.py - do not edit.\n\n'

INCLUDE = '#include "mtproto/mtproto_custom_dc_config.h"\n\n'


def _cpp_string_literal(s):
    """Emit s as a sequence of C++ string literals, one per source line."""
    lines = s.split('\n')
    parts = []
    for index, line in enumerate(lines):
        escaped = line.replace('\\', '\\\\').replace('"', '\\"')
        suffix = '\\n' if index + 1 < len(lines) else ''
        parts.append('\t"{}{}"'.format(escaped, suffix))
    return '\n'.join(parts)


def _endpoints_literal(dc):
    """
    Generate the CustomDcEndpoint array body for one DC from the API response.

    API shape:
      {
        "id": 2,
        "rsaPublicKey": "-----BEGIN RSA PUBLIC KEY-----\\n...\\n-----END RSA PUBLIC KEY-----",
        "endpoints": [{"ip": "...", "port": ..., "wsTlsOnly": false}, ...],
        ...
      }

    wsTlsOnly endpoints are hostnames reachable only over the websocket/TLS
    carrier, which the MTProto socket layer cannot dial, so they are skipped.
    """
    rows = []
    for endpoint in dc.get('endpoints', []):
        if endpoint.get('wsTlsOnly', False):
            continue
        ip = endpoint['ip']
        # DcOptions keeps IPv4 and IPv6 endpoints apart via Flag::f_ipv6.
        ipv6 = 'true' if ':' in ip else 'false'
        rows.append('\t{{ "{}", {}, {} }},'.format(ip, endpoint['port'], ipv6))
    return rows


def generate_custom_dc_config_cpp(url_config_path, output_path):
    """
    Fetch the DC list from the URL stored in url_config_path and write a C++
    file at output_path defining MTP::CustomDcConfigData(). When the URL file
    is absent the generated source returns nullptr, meaning "this build targets
    the standard Telegram network".
    """
    if not os.path.exists(url_config_path):
        content = (
            HEADER
            + INCLUDE
            + 'namespace MTP {\n\n'
            'const CustomDcConfig *CustomDcConfigData() {\n'
            '\treturn nullptr;\n'
            '}\n\n'
            '} // namespace MTP\n'
        )
    else:
        with open(url_config_path) as f:
            url = f.read().strip()
        try:
            request = urllib.request.Request(url, headers={
                'Accept': 'application/json',
                'User-Agent': 'TBlah-Desktop-BuildSystem/1.0',
            })
            with urllib.request.urlopen(request, timeout=15) as response:
                config = json.loads(response.read().decode('utf-8'))
        except Exception as e:
            raise RuntimeError(
                'Failed to fetch DC config from {}: {}'.format(url, e))

        dcs = config.get('dcs', [])
        if not dcs:
            raise RuntimeError(
                'DC config response from {} contained no DCs'.format(url))

        blocks = []
        entries = []
        for dc in dcs:
            identifier = dc['id']
            rows = _endpoints_literal(dc)
            if not rows:
                raise RuntimeError(
                    'DC {} has no dialable endpoints'.format(identifier))
            blocks.append(
                'const CustomDcEndpoint kEndpoints{}[] = {{\n{}\n}};\n'.format(
                    identifier, '\n'.join(rows)))
            blocks.append('const char kPublicKey{}[] =\n{};\n'.format(
                identifier, _cpp_string_literal(dc['rsaPublicKey'].strip())))
            entries.append('\t{{ {}, kEndpoints{}, {}, kPublicKey{} }},'.format(
                identifier, identifier, len(rows), identifier))

        content = (
            HEADER
            + INCLUDE
            + 'namespace MTP {\n'
            'namespace {\n\n'
            + '\n'.join(blocks)
            + '\nconst CustomDc kDcs[] = {{\n{}\n}};\n\n'.format(
                '\n'.join(entries))
            + 'const CustomDcConfig kConfig = {{ {}, kDcs, {} }};\n\n'.format(
                dcs[0]['id'], len(entries))
            + '} // namespace\n\n'
            'const CustomDcConfig *CustomDcConfigData() {\n'
            '\treturn &kConfig;\n'
            '}\n\n'
            '} // namespace MTP\n'
        )

    directory = os.path.dirname(os.path.abspath(output_path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(output_path, 'w') as f:
        f.write(content)


def main():
    parser = argparse.ArgumentParser(
        description='Generate the custom DC config translation unit.')
    parser.add_argument('--url-file', required=True)
    parser.add_argument('--output', required=True)
    arguments = parser.parse_args()
    generate_custom_dc_config_cpp(arguments.url_file, arguments.output)


if __name__ == '__main__':
    main()
